// Server only: the MCP server of Ticket Forge for Claude Code. The tools call
// the same functions as the UI; there is deliberately no transfer to Odoo.
import { readFile } from "node:fs/promises";
import path from "node:path";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import type { CallToolResult } from "@modelcontextprotocol/sdk/types.js";
import { z } from "zod";
import { prepareRequirement } from "@/lib/requirement-preparation";
import { createRequirement, findRequirement, findRequirements, updateRequirement } from "@/lib/requirement-repository";
import { getDisplayTitle, type Requirement } from "@/modules/TicketForge/requirements";

const TEMPLATE_PATH = path.join(process.cwd(), "prompts", "ticket-forge.md");

// The template's sections from here on hold the placeholders of one requirement.
const TEMPLATE_INPUT_HEADING = "\n## Rohtext";

const INSTRUCTIONS = `Ticket Forge turns customer requirements (meeting notes, emails) into Odoo tickets for internal developers.
- Use it when the user asks in German for an "Anforderungsticket", to "eine Anforderung anlegen", "ein Ticket erstellen" or "ein Odoo-Ticket vorbereiten" for a customer requirement.
- Create a requirement with the raw text; by default the app prepares it with its own AI and rules.
- To write the ticket yourself, call get_ticket_guidelines first and pass description and internalDescription with prepare: false.
- Ticket content is German Markdown. The description is visible to the customer; only truly internal information goes into internalDescription.
- There is no transfer tool: the user transfers to Odoo in the app. Give the user the url of the requirement.`;

function appUrl(id: string): string {
  const base = (process.env.TICKET_FORGE_APP_URL || "https://datamints-coworker.ddev.site:3000").replace(/\/+$/, "");

  return `${base}/ticket-forge/${id}`;
}

// What Claude Code sees of a requirement; hashes and internal state stay out.
function present(requirement: Requirement) {
  return {
    id: requirement.id,
    url: appUrl(requirement.id),
    title: requirement.title,
    status: requirement.status,
    source: requirement.source,
    description: requirement.description,
    internalDescription: requirement.internalDescription,
    aiFeedback: requirement.aiFeedback,
    odooTicket: requirement.ticket && {
      type: requirement.ticket.type,
      number: requirement.ticket.number,
      title: requirement.ticket.title,
    },
    archived: requirement.archived,
    updatedAt: requirement.updatedAt,
  };
}

function result(value: unknown): CallToolResult {
  return { content: [{ type: "text", text: JSON.stringify(value, null, 2) }] };
}

function failure(message: string): CallToolResult {
  return { content: [{ type: "text", text: message }], isError: true };
}

const NOT_FOUND = "Requirement not found. Use list_requirements to find the id.";

// Runs a tool and turns a thrown error (e.g. a missing AI setting) into a tool error.
async function attempt(action: () => Promise<CallToolResult>): Promise<CallToolResult> {
  try {
    return await action();
  } catch (error) {
    console.error(error);

    return failure(error instanceof Error ? error.message : "The request failed");
  }
}

// A new server per request: the route is stateless.
export function createTicketForgeMcpServer(): McpServer {
  const server = new McpServer({ name: "ticket-forge", version: "1.0.0" }, { instructions: INSTRUCTIONS });

  server.registerTool(
    "create_requirement",
    {
      title: "Create requirement",
      description:
        "Creates a requirement (German: Anforderungsticket, Anforderung, Kundenanforderung) in Ticket Forge, " +
        "to become an Odoo ticket; use it for 'erstelle ein Anforderungsticket', 'lege eine Anforderung an', " +
        "'erstelle ein Ticket'. Takes a raw text (meeting notes, email). With prepare (default true) the app's AI " +
        "structures it into title, description and internal description, which takes about 10 seconds. With " +
        "prepare false, pass description and internalDescription written by the rules of get_ticket_guidelines.",
      inputSchema: {
        rawText: z
          .string()
          .min(1)
          .describe(
            "The original text, unchanged, including sender, date and context given around it " +
              "(e.g. 'Mail von Fr. Kaiser, Stadtwerke'); do not summarize or shorten it",
          ),
        title: z.string().optional().describe("Optional; generated by the AI if empty"),
        prepare: z.boolean().default(true).describe("Let the app's AI prepare the requirement"),
        description: z.string().optional().describe("German Markdown, only with prepare false"),
        internalDescription: z.string().optional().describe("German Markdown, only with prepare false"),
      },
    },
    ({ rawText, title, prepare, description, internalDescription }) =>
      attempt(async () => {
        const created = await createRequirement({
          rawText,
          title: title?.trim() ?? "",
          description: prepare ? undefined : description,
          internalDescription: prepare ? "" : internalDescription,
          source: "claude-code",
        });

        if (!prepare) {
          return result(present(created));
        }

        try {
          return result(present((await prepareRequirement(created.id)) ?? created));
        } catch (error) {
          // The requirement exists anyway; it can be prepared in the app.
          const message = error instanceof Error ? error.message : "Preparation failed";

          return failure(`The requirement was created (${appUrl(created.id)}), but the preparation failed: ${message}`);
        }
      }),
  );

  server.registerTool(
    "get_requirement",
    {
      title: "Get requirement",
      description: "Returns a requirement with all fields, the AI feedback, the linked Odoo ticket and its url in the app.",
      inputSchema: { id: z.string() },
      annotations: { readOnlyHint: true },
    },
    ({ id }) =>
      attempt(async () => {
        const requirement = await findRequirement(id);

        return requirement ? result(present(requirement)) : failure(NOT_FOUND);
      }),
  );

  server.registerTool(
    "list_requirements",
    {
      title: "List requirements",
      description: "Lists the requirements that are not archived, latest change first.",
      annotations: { readOnlyHint: true },
    },
    () =>
      attempt(async () =>
        result(
          (await findRequirements(false)).map((requirement) => ({
            id: requirement.id,
            title: getDisplayTitle(requirement),
            status: requirement.status,
            source: requirement.source,
            updatedAt: requirement.updatedAt,
            url: appUrl(requirement.id),
          })),
        ),
      ),
  );

  server.registerTool(
    "update_requirement",
    {
      title: "Update requirement",
      description: "Changes title, description or internal description; fields that are left out stay as they are.",
      inputSchema: {
        id: z.string(),
        title: z.string().optional(),
        description: z.string().optional().describe("German Markdown"),
        internalDescription: z.string().optional().describe("German Markdown"),
      },
      annotations: { idempotentHint: true },
    },
    ({ id, ...changes }) =>
      attempt(async () => {
        const updated = await updateRequirement(id, changes);

        return updated ? result(present(updated)) : failure(NOT_FOUND);
      }),
  );

  server.registerTool(
    "refine_requirement",
    {
      title: "Refine requirement",
      description:
        "Lets the app's AI revise title, description and internal description by an instruction, " +
        "e.g. 'Punkt 3 ist out of scope'. Takes about 10 seconds; the user can undo it in the app.",
      inputSchema: { id: z.string(), instruction: z.string().min(1) },
    },
    ({ id, instruction }) =>
      attempt(async () => {
        const refined = await prepareRequirement(id, instruction);

        return refined ? result(present(refined)) : failure(NOT_FOUND);
      }),
  );

  server.registerTool(
    "get_ticket_guidelines",
    {
      title: "Get ticket guidelines",
      description:
        "Returns the rules for title, description and internal description, as used by the app's AI. " +
        "Read them before writing a ticket yourself (create_requirement with prepare false or update_requirement).",
      annotations: { readOnlyHint: true },
    },
    () =>
      attempt(async () => {
        const template = await readFile(TEMPLATE_PATH, "utf8");
        const end = template.indexOf(TEMPLATE_INPUT_HEADING);

        return { content: [{ type: "text", text: end === -1 ? template : template.slice(0, end).trim() }] };
      }),
  );

  return server;
}
